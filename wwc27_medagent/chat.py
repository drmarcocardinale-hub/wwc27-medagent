"""A hosted chat front end over the same tools the MCP server exposes.

Why this sits in the same process as the server rather than beside it: the tool list and the
schemas handed to the model are read from the live MCP server at startup, and every call goes
through ``mcp.call_tool`` - the same path any MCP client takes. There is no second copy of the
tool definitions to drift out of step, which is the same reason the reader site's heat panel
reads a grid generated by ``core`` instead of re-implementing the formula.

What it is not: a replacement for the reader site or the archive. Both must keep answering with
this turned off, out of quota, or the key revoked. This is a convenience for someone who will
not configure an MCP client, nothing more.

Three constraints shape the rest:

* The visitor never sees a key. The house key lives in an environment variable; a visitor who
  runs out of free questions supplies their own, which is held for the request and never stored.
* An open box on a page cited in a journal will be crawled. Free questions are rationed per
  caller per day and the tool loop is capped, so a runaway conversation cannot bill forever.
* Clinicians will type player details into any box regardless of the warning above it. Nothing
  here writes a transcript to disk, and the only thing kept in memory is a counter per caller.

Set GEMINI_API_KEY to enable the house key. Without it the page still loads and simply asks
every visitor for their own, which is a reasonable way to run it for free.
"""
from __future__ import annotations

import json
import os
import time
import urllib.error
import urllib.request
from typing import Any

import anyio

from . import core

# Pinned, not an alias. The default was gemini-flash-latest, and Google's own documentation says
# a "-latest" alias is hot-swapped with every new release of that variation: the model behind a
# running service changes without warning, and the service's behaviour changes with it. That is
# what happened here - the agent worked, then began taking over 90 seconds per question, with no
# change to this code, the key or the network. A resource cited in a paper has to be reproducible,
# so the version is pinned here and moved deliberately. GEMINI_MODEL overrides it.
#
# Flash-Lite is the right tier for this workload: the agent reads values from a curated table and
# reports them with a source, which is retrieval, not reasoning.
MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash-lite")
# Overridable so the tool-calling loop can be exercised against a stub; nothing else
# in this file is worth testing without one.
API_ROOT = os.environ.get(
    "GEMINI_API_ROOT", "https://generativelanguage.googleapis.com/v1beta/models")

# Rationing, in two layers because one is not enough.
#
# FREE_PER_DAY is per caller, and a caller is an IP address, so it only slows down someone
# honest. Anything with a pool of addresses - a crawler, a scraper farm, someone annoyed -
# gets FREE_PER_DAY questions per address and bills the house key for all of them. So there
# is a second, global ceiling on questions answered off the house key per day, which no
# number of addresses can get past.
#
# Neither of these is the last line of defence: that is the absence of a billing account on
# the key's project, which makes overspend impossible rather than merely bounded. These two
# exist so the free allowance is not exhausted by lunchtime by something that is not a reader.
FREE_PER_DAY = int(os.environ.get("CHAT_FREE_PER_DAY", "8"))
GLOBAL_PER_DAY = int(os.environ.get("CHAT_GLOBAL_PER_DAY", "150"))
# 6 was too mean in practice: "we are based in Sao Paulo and play in Fortaleza, Recife and Porto
# Alegre, draft our plan" is a venue profile per city plus travel and screening, and the model
# asks for them in one batch. The ceiling exists to bound a runaway conversation, not to refuse
# ordinary questions, and the per-caller and per-day limits are what actually bound the spend.
MAX_TOOL_CALLS = int(os.environ.get("CHAT_MAX_TOOL_CALLS", "12"))
MAX_HISTORY = int(os.environ.get("CHAT_MAX_HISTORY", "12"))
MAX_CHARS = int(os.environ.get("CHAT_MAX_CHARS", "1200"))
TIMEOUT_S = float(os.environ.get("CHAT_TIMEOUT_S", "90"))

# A ceiling for the whole answer, not just one call. Cloud Run cuts the request off at 300s and
# shows its own error page, which is worse than anything this code can say; staying under that
# with room for a closing turn means the reader gets the work that did finish. Raise it only
# alongside the service's --timeout.
DEADLINE_S = float(os.environ.get("CHAT_DEADLINE_S", "200"))
WRAP_UP_TIMEOUT_S = float(os.environ.get("CHAT_WRAP_UP_TIMEOUT_S", "45"))

# 0 turns thinking off, -1 omits the setting and lets the model decide. See _generation_config.
THINKING_BUDGET = int(os.environ.get("CHAT_THINKING_BUDGET", "0"))
# 900 was thin for a plan covering four cities; the answer is the whole deliverable here.
MAX_OUTPUT_TOKENS = int(os.environ.get("CHAT_MAX_OUTPUT_TOKENS", "1600"))

# Transient failures worth absorbing rather than showing. "This model is currently experiencing
# high demand" is the common one and usually clears in seconds, but a reader does not retry: they
# read the error once and conclude the agent is broken. Since this page is cited in an article,
# that impression is expensive and the fix is cheap.
#
# Only codes that a retry can plausibly fix. A rejected key or a malformed request will be
# rejected again just as fast, and retrying those would add delay to an error the reader needs
# to see now.
RETRY_ON = frozenset({429, 500, 502, 503, 504})
RETRIES = int(os.environ.get("CHAT_RETRIES", "2"))          # extra attempts after the first
RETRY_BACKOFF_S = float(os.environ.get("CHAT_RETRY_BACKOFF_S", "0.6"))

SYSTEM = (
    "You are the paper agent for the Current Opinion 'Sports Medicine and Science Considerations "
    "to Maximise Preparation for the FIFA Women's World Cup Brazil 2027' (Cardinale & Geertsema). "
    "Answer only from the tools provided. Call a tool rather than recalling a number. "
    "Report the source link each tool returns, and name the tool you used. "
    "If the tools do not cover a question - tactics, selection, an unrelated condition, another "
    "tournament - say you don't know and say what the agent does cover, rather than improvising. "
    "Never ask for, and never repeat back, identifiable player information. "
    "Outputs are decision support for qualified clinicians, not clinical decisions. "
    "Be brief: a few sentences, or a short list. Units: Celsius, kilometres."
)

LIMIT_HIT = ("That question needed more tool calls than the limit allows. "
             "Try asking for one city or one topic at a time.")

SLOW_PARTIAL = ("That question took longer than the time allowed, and the agent stopped before "
                "it could finish. The tools it did reach are listed below. Asking about one "
                "city, or one topic, at a time will answer quickly.")

_quota: dict[str, tuple[str, int]] = {}      # caller -> (yyyy-mm-dd, questions used)
_spent: tuple[str, int] = ("", 0)            # (yyyy-mm-dd, questions answered off the house key)


# --------------------------------------------------------------------------- tool plumbing

def _schema_of(tool: Any) -> dict:
    """mcp 1.x calls it inputSchema, 2.x input_schema. Both ship in CI, so read whichever."""
    return getattr(tool, "input_schema", None) or getattr(tool, "inputSchema", None) or {}


_ALLOWED = {"type", "description", "enum", "items", "properties", "required", "nullable", "format"}


def _clean(schema: Any) -> Any:
    """Reduce a JSON Schema to the subset Gemini's function declarations accept.

    Pydantic adds 'title' to every field and '$defs'/'anyOf' for optionals; Gemini rejects the
    first and mishandles the rest. An optional field becomes a plain nullable one, which is what
    the tool means anyway.
    """
    if not isinstance(schema, dict):
        return schema
    if "anyOf" in schema:
        variants = [v for v in schema["anyOf"] if isinstance(v, dict) and v.get("type") != "null"]
        base = _clean(variants[0]) if variants else {"type": "string"}
        if len(variants) < len(schema["anyOf"]):
            base["nullable"] = True
        if schema.get("description"):
            base["description"] = schema["description"]
        return base
    out: dict[str, Any] = {}
    for key, value in schema.items():
        if key not in _ALLOWED:
            continue
        if key == "properties" and isinstance(value, dict):
            out[key] = {k: _clean(v) for k, v in value.items()}
        elif key == "items":
            out[key] = _clean(value)
        else:
            out[key] = value
    out.setdefault("type", "object" if "properties" in out else "string")
    return out


async def declarations() -> list[dict]:
    """Gemini function declarations, derived from the live MCP tool list."""
    from .server import mcp
    out = []
    for tool in await mcp.list_tools():
        schema = _clean(_schema_of(tool))
        decl: dict[str, Any] = {"name": tool.name,
                                "description": (tool.description or "").strip()[:900]}
        # A no-argument tool must omit parameters entirely; an empty object is rejected.
        if schema.get("properties"):
            decl["parameters"] = schema
        out.append(decl)
    return out


async def run_tool(name: str, args: dict) -> str:
    """Call through the MCP server itself, so the chat cannot answer from a different code path."""
    from .server import mcp
    result = await mcp.call_tool(name, args or {})
    content = getattr(result, "content", result)
    if isinstance(content, (list, tuple)):
        parts = [getattr(c, "text", None) for c in content]
        text = "\n".join(p for p in parts if p)
        if text:
            return text[:6000]
    return json.dumps(content, default=str)[:6000]


# --------------------------------------------------------------------------- the model call

def _generation_config() -> dict:
    """Generation settings, with thinking turned down by default.

    Measured against the deployed service: the simplest question in the set - one city, one
    tool - did not return a first response in 90 seconds, with no tool called. The same key
    answering a bare prompt replies instantly, so the cost is the model deliberating over nine
    tool declarations before its first move, not the tools or the loop.

    This agent reads values out of a curated table and reports them with a source. That is
    retrieval, not reasoning, so a large thinking budget buys little and costs the reader a
    minute. CHAT_THINKING_BUDGET raises it for anyone who wants more deliberation; -1 omits the
    setting and leaves the model to decide, which is the behaviour that was too slow to use.
    """
    config: dict = {"temperature": 0.2, "maxOutputTokens": MAX_OUTPUT_TOKENS}
    if THINKING_BUDGET >= 0:
        config["thinkingConfig"] = {"thinkingBudget": THINKING_BUDGET}
    return config


def _post(url: str, payload: dict, key: str, timeout: float | None = None) -> dict:
    timeout = TIMEOUT_S if timeout is None else timeout
    body = json.dumps(payload).encode()
    req = urllib.request.Request(
        url, data=body, method="POST",
        headers={"Content-Type": "application/json", "x-goog-api-key": key})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode())
    except urllib.error.HTTPError as exc:                      # surface Google's own message
        detail = exc.read().decode(errors="replace")[:600]
        raise ChatError(_explain(exc.code, detail), status=exc.code) from None
    except TimeoutError as exc:
        # socket.timeout IS TimeoutError on 3.10+, and urlopen raises it bare rather than
        # wrapping it in URLError, so it slipped past the handler below and reached the page as
        # the words "The agent failed: TimeoutError".
        raise ChatError(
            f"The model took more than {timeout:.0f} seconds and the request was cut off. "
            "A question spanning several cities or topics takes longer; try asking about one at "
            "a time.", status=504, retryable=False) from None
    except urllib.error.URLError as exc:
        reason = exc.reason
        if isinstance(reason, TimeoutError):          # connect timeouts arrive wrapped
            raise ChatError(
                f"The model API did not respond within {timeout:.0f} seconds.",
                status=504, retryable=False) from None
        raise ChatError(f"Could not reach the model API: {reason}", status=502) from None
    except ValueError as exc:                          # includes JSONDecodeError
        raise ChatError(f"The model API sent a reply this agent could not read: {exc}",
                        status=502) from None


def _reason(detail: str) -> tuple[str, str]:
    """Google's own machine reason and human message, or empty strings.

    Worth the parsing: a 400 from this API is INVALID_ARGUMENT, which covers both a bad key and a
    request this code built wrongly. Those need opposite actions from whoever is reading the page,
    and the previous version of this function told them to check their key either way.
    """
    try:
        err = (json.loads(detail) or {}).get("error") or {}
    except Exception:
        return "", ""
    reason = ""
    for d in err.get("details") or []:
        if isinstance(d, dict) and d.get("reason"):
            reason = str(d["reason"])
            break
    return reason, str(err.get("message") or "")


def _explain(code: int, detail: str) -> str:
    reason, message = _reason(detail)
    tail = f" Google said: {message}" if message else ""

    if reason == "API_KEY_INVALID" or "api key not valid" in message.lower():
        return ("The model API rejected the key itself. If you supplied your own, check it is a "
                "Gemini API key from aistudio.google.com and was pasted whole." + tail)
    if reason in ("SERVICE_DISABLED", "API_KEY_SERVICE_BLOCKED") or code == 403:
        return ("The key is recognised but not allowed to use this API. Enable the Generative "
                "Language API on its project, and check the key has no API or referrer "
                "restriction that excludes it." + tail)
    if code == 429:
        return ("The model API is rate limited right now - that is Google's per-key quota, not "
                "this page. Wait a minute, or supply your own key.")
    if code >= 500:
        return "The model API returned a server error. Try again in a moment." + tail
    if code == 400:
        # Not a key problem: the request itself was refused, which is this server's fault.
        return ("The model API refused the request. This is a fault in the agent, not in your "
                "key - please report it." + tail)
    return f"The model API returned {code}.{tail}"


class ChatError(Exception):
    def __init__(self, message: str, status: int = 400, retryable: bool | None = None):
        super().__init__(message)
        self.status = status
        # Status alone is not enough to decide. A timeout is reported as 504, which is normally
        # worth retrying, but it has already spent the full timeout waiting - trying twice more
        # would leave someone staring at a blank page for three minutes to reach the same end.
        self.retryable = (status in RETRY_ON) if retryable is None else retryable


async def _generate(contents: list[dict], tools: list[dict] | None, key: str,
                    timeout: float | None = None) -> dict:
    payload = {
        "systemInstruction": {"parts": [{"text": SYSTEM}]},
        "contents": contents,
        "generationConfig": _generation_config(),
    }
    # Offering no tools is how the final turn is forced to produce prose: a model that can still
    # see the tools will keep asking for them.
    if tools:
        payload["tools"] = [{"functionDeclarations": tools}]
    url = f"{API_ROOT}/{MODEL}:generateContent"
    for attempt in range(RETRIES + 1):
        try:
            # urllib blocks, and this runs inside the event loop that also serves /mcp.
            return await anyio.to_thread.run_sync(lambda: _post(url, payload, key, timeout))
        except ChatError as exc:
            if not exc.retryable or attempt == RETRIES:
                raise
            # Back off a little between tries: an overloaded model is not helped by being asked
            # again immediately, and the whole budget here is under three seconds.
            await anyio.sleep(RETRY_BACKOFF_S * (2 ** attempt))
    raise AssertionError("unreachable")              # the loop either returns or raises


NO_MORE_TOOLS = (
    "You have used the tool budget for this question. Do not ask for more tools. Answer now "
    "from the tool results above, keeping the sources, and finish by naming plainly whatever "
    "part of the question you could not cover, so the reader can ask about it separately.")


async def _wrap_up(contents: list[dict], key: str, trace: list[dict],
                   fallback: str = LIMIT_HIT) -> dict:
    """One last turn with no tools offered, so the work already done still yields an answer."""
    closing = contents + [{"role": "user", "parts": [{"text": NO_MORE_TOOLS}]}]
    try:
        # Bounded separately: this runs when time is already short, and it is the last thing
        # standing between the reader and Cloud Run's error page.
        data = await _generate(closing, None, key, timeout=WRAP_UP_TIMEOUT_S)
        parts = ((data.get("candidates") or [{}])[0].get("content") or {}).get("parts") or []
        text = "".join(p.get("text", "") for p in parts).strip()
    except ChatError:
        text = ""                                    # a plain message beats a raised error here
    return {"answer": text or fallback, "tools": trace}


async def answer(history: list[dict], key: str) -> dict:
    """Run the tool-calling loop. Returns the reply plus the trace of what was called."""
    tools = await declarations()
    contents = [{"role": h["role"], "parts": [{"text": h["text"][:MAX_CHARS]}]}
                for h in history[-MAX_HISTORY:]]
    trace: list[dict] = []
    started = time.monotonic()

    for _ in range(MAX_TOOL_CALLS + 1):
        # Stop starting new work once the answer as a whole is running out of time. Only once
        # something has been gathered: with an empty trace there is nothing to wrap up, and the
        # error is the honest reply.
        left = DEADLINE_S - (time.monotonic() - started)
        if trace and left <= 0:
            return await _wrap_up(contents, key, trace, fallback=SLOW_PARTIAL)
        try:
            # Never let one call run past the deadline: without this, a call starting just
            # inside it could run its full timeout and the closing turn another, overshooting
            # the request limit Cloud Run enforces and replacing any answer with its error page.
            data = await _generate(contents, tools, key, timeout=max(1.0, min(TIMEOUT_S, left)))
        except ChatError as exc:
            # A call that timed out or failed transiently, with results already in hand, should
            # still produce an answer from those rather than discarding them.
            if trace and exc.status in (502, 503, 504):
                return await _wrap_up(contents, key, trace, fallback=SLOW_PARTIAL)
            raise
        candidates = data.get("candidates") or []
        if not candidates:
            blocked = (data.get("promptFeedback") or {}).get("blockReason")
            raise ChatError("The model returned nothing"
                            + (f" ({blocked})." if blocked else "."), status=502)
        parts = (candidates[0].get("content") or {}).get("parts") or []
        # Keep the whole part, not just the call inside it: the sibling thoughtSignature has to
        # travel back with it (see where the model turn is appended below).
        call_parts = [p for p in parts if "functionCall" in p]
        calls = [p["functionCall"] for p in call_parts]

        if not calls:
            text = "".join(p.get("text", "") for p in parts).strip()
            if not text and candidates[0].get("finishReason") == "MAX_TOKENS":
                text = "The answer ran past the length limit. Try a narrower question."
            return {"answer": text or "No answer was produced.", "tools": trace}

        # Spend the budget on calls, not on loop turns: a model that asks for one tool per turn
        # would otherwise get MAX_TOOL_CALLS + 1 of them.
        #
        # Reaching the ceiling is not a reason to throw the work away. A plan covering four
        # cities legitimately wants a call each, and refusing the batch outright discarded every
        # result already gathered and showed the reader an error instead - which is exactly what
        # it did in practice. Ask for prose from what is in hand, and say what went uncovered.
        if len(trace) + len(calls) > MAX_TOOL_CALLS:
            return await _wrap_up(contents, key, trace)

        # Echo the model's own turn back verbatim rather than rebuilding it from the calls.
        #
        # Thinking models attach a thoughtSignature alongside each functionCall, and the API
        # requires it to come back with the turn; reconstructing a part as {"functionCall": c}
        # keeps the call and silently drops its signature, which the API rejects with a 400.
        # Copying what was received also carries any future sibling field for free, which is the
        # whole reason the old version broke: it only kept the one key it knew about.
        model_turn = dict(candidates[0].get("content") or {})
        model_turn["role"] = "model"
        model_turn["parts"] = call_parts
        contents.append(model_turn)
        responses = []
        for call in calls:
            name, args = call.get("name", ""), call.get("args") or {}
            try:
                output = await run_tool(name, args)
            except Exception as exc:                 # a bad argument is the model's to recover from
                output = json.dumps({"error": f"{type(exc).__name__}: {exc}"})
            trace.append({"name": name, "args": args})
            responses.append({"functionResponse": {"name": name, "response": {"result": output}}})
        contents.append({"role": "user", "parts": responses})

    return {"answer": LIMIT_HIT, "tools": trace}


# --------------------------------------------------------------------------- rationing

def _today() -> str:
    return time.strftime("%Y-%m-%d", time.gmtime())


def take_free_question(caller: str) -> bool:
    """One free question off the house key.

    False when either ceiling is reached - this caller's for the day, or the instance's. Both
    are enforced here rather than at the route, so there is one place to get it wrong.
    """
    global _spent
    if global_left() <= 0:
        return False
    day, used = _quota.get(caller, ("", 0))
    if day != _today():
        used = 0
    if used >= FREE_PER_DAY:
        _quota[caller] = (_today(), used)
        return False
    _quota[caller] = (_today(), used + 1)
    gday, gused = _spent
    _spent = (_today(), (gused if gday == _today() else 0) + 1)
    if len(_quota) > 20000:                         # a crawler must not grow this without bound
        cutoff = _today()
        for k in [k for k, (d, _) in _quota.items() if d != cutoff][:10000]:
            _quota.pop(k, None)
    return True


def free_left(caller: str) -> int:
    """What this caller may still ask today, never more than the instance has left."""
    day, used = _quota.get(caller, ("", 0))
    mine = FREE_PER_DAY if day != _today() else max(0, FREE_PER_DAY - used)
    return min(mine, global_left())


def global_left() -> int:
    """Questions this instance may still answer off the house key today."""
    day, used = _spent
    return GLOBAL_PER_DAY if day != _today() else max(0, GLOBAL_PER_DAY - used)


def house_key() -> str:
    return os.environ.get("GEMINI_API_KEY", "").strip()


def version() -> str:
    return core.__version__
